function storedLanguage() {
  try {
    return localStorage.getItem("venus-language");
  } catch {
    return null;
  }
}
let language =
  storedLanguage() || (navigator.language.startsWith("zh") ? "zh" : "en");
if (!messages[language]) language = "en";
export function t(key) {
  return messages[language][key] || messages.en[key] || key;
}
export function getLanguage() {
  return language;
}
export function setLanguage(value) {
  language = messages[value] ? value : "en";
  document.documentElement.lang = language;
  try {
    localStorage.setItem("venus-language", language);
  } catch {}
  document
    .querySelectorAll("[data-i18n]")
    .forEach((node) => (node.textContent = t(node.dataset.i18n)));
  document.querySelectorAll("[data-label]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.label));
    node.title = t(node.dataset.label);
  });
  const button = document.getElementById("language-button");
  button.textContent = language === "en" ? "中" : "EN";
  button.setAttribute(
    "aria-label",
    language === "en" ? "切换到中文" : "Switch to English",
  );
  window.dispatchEvent(new CustomEvent("venus-language"));
}
setLanguage(language);
